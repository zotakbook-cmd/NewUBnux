/* =========================================================
   UBnux - SEO Router
   File: assets/js/router.js
   Version: 2.2.0

   Responsibilities:
   - Parse UBnux SEO URLs
   - Detect current page type
   - Extract state / district / category / business slug
   - Generate canonical page URLs
   - Keep routing logic centralized
   - Support permanent /in/ SEO architecture
   - Support business-page.js compatibility
   - NEVER generate legacy /business/ URLs
   - Future Cloudflare Worker compatible

   URL STRUCTURE
   ---------------------------------------------------------
   /
   /in/
   /in/bihar/
   /in/bihar/siwan/
   /in/bihar/siwan/libraries/
   /in/bihar/siwan/libraries/abc-library/

   LEGACY
   ---------------------------------------------------------
   /business/abc-library/

   IMPORTANT:
   - Does NOT fetch data
   - Does NOT render businesses
   - Does NOT modify filters
   - Does NOT redirect browser
   - Does NOT interfere with app.js
========================================================= */


(function (window) {

  "use strict";


  /* =======================================================
     NAMESPACE
  ======================================================= */

  window.UBnux =
    window.UBnux ||
    window.ZilaBiz ||
    {};


  window.ZilaBiz =
    window.UBnux;


  var App =
    window.UBnux;


  /* =======================================================
     CONSTANTS
  ======================================================= */

  var SITE_ORIGIN =
    "https://ubnux.com";


  var SEO_PREFIX =
    "in";


  /*
   * Reserved/static paths.
   *
   * IMPORTANT:
   *
   * "business" is recognized only as a legacy route
   * when somebody manually opens /business/.
   *
   * It is NEVER generated by this router.
   */

  var RESERVED_PATHS = {

    business: true,

    search: true,

    about: true,

    contact: true,

    privacy: true,

    "privacy-policy": true,

    terms: true,

    login: true,

    admin: true,

    api: true,

    assets: true,

    sitemap: true,

    "sitemap.xml": true,

    "robots.txt": true

  };


  /* =======================================================
     BASIC HELPERS
  ======================================================= */

  function clean(
    value
  ) {

    if (
      value === null ||
      value === undefined
    ) {

      return "";

    }


    return String(
      value
    ).trim();

  }


  /* =======================================================
     CLEAN SLUG
  ======================================================= */

  function cleanSlug(
    value
  ) {

    var slug =
      clean(
        value
      )
        .toLowerCase()
        .replace(
          /^\/+|\/+$/g,
          ""
        )
        .replace(
          /\s+/g,
          "-"
        )
        .replace(
          /[^a-z0-9-]/g,
          ""
        )
        .replace(
          /-+/g,
          "-"
        );


    return slug;

  }


  /* =======================================================
     SAFE DECODE
  ======================================================= */

  function safeDecode(
    value
  ) {

    try {

      return decodeURIComponent(
        clean(
          value
        )
      );

    } catch (
      error
    ) {

      return clean(
        value
      );

    }

  }


  /* =======================================================
     PATH NORMALIZATION
  ======================================================= */

  function normalizePath(
    pathname
  ) {

    var path =
      clean(
        pathname ||
        "/"
      );


    /*
     * Decode URL safely.
     */

    path =
      safeDecode(
        path
      );


    /*
     * Remove duplicate slashes.
     *
     * //in//bihar//
     *
     * becomes:
     *
     * /in/bihar/
     */

    path =
      path.replace(
        /\/+/g,
        "/"
      );


    /*
     * Always start with /
     */

    if (
      path.charAt(
        0
      ) !== "/"
    ) {

      path =
        "/" +
        path;

    }


    /*
     * File URLs should not
     * automatically receive
     * trailing slash.
     */

    if (
      /\.[a-z0-9]+$/i.test(
        path
      )
    ) {

      return path;

    }


    /*
     * Normal UBnux SEO routes
     * always end with slash.
     */

    if (
      path !== "/" &&
      path.charAt(
        path.length - 1
      ) !== "/"
    ) {

      path += "/";

    }


    return path;

  }


  /* =======================================================
     GET URL SEGMENTS
  ======================================================= */

  function getSegments(
    pathname
  ) {

    var path =
      normalizePath(
        pathname
      );


    return path
      .split(
        "/"
      )
      .filter(
        function (
          item
        ) {

          return Boolean(
            clean(
              item
            )
          );

        }
      )
      .map(
        function (
          item
        ) {

          return cleanSlug(
            item
          );

        }
      );

  }


  /* =======================================================
     ABSOLUTE URL BUILDER
  ======================================================= */

  function joinURL(
    path
  ) {

    var normalized =
      normalizePath(
        path
      );


    return (
      SITE_ORIGIN +
      normalized
    );

  }


  /* =======================================================
     SEO PATH CHECK
  ======================================================= */

  function isSEOPath(
    segments
  ) {

    return (
      Array.isArray(
        segments
      ) &&
      segments.length >= 1 &&
      segments[0] ===
        SEO_PREFIX
    );

  }


  /* =======================================================
     BASE ROUTE OBJECT
  ======================================================= */

  function createBaseRoute(
    path,
    segments
  ) {

    return {

      type:
        "unknown",

      isSEOPage:
        false,

      isBusinessPage:
        false,

      isStatePage:
        false,

      isDistrictPage:
        false,

      isCategoryPage:
        false,

      isStaticPage:
        false,

      isLegacyPage:
        false,

      path:
        path,

      canonicalPath:
        path,

      canonicalURL:
        joinURL(
          path
        ),

      stateSlug:
        "",

      districtSlug:
        "",

      categorySlug:
        "",

      businessSlug:
        "",

      segments:
        segments.slice()

    };

  }


  /* =======================================================
     ROUTE DETECTION
  ======================================================= */

  function parseRoute(
    pathname
  ) {

    var path =
      normalizePath(

        pathname ||

        (
          window.location &&
          window.location.pathname
        ) ||

        "/"

      );


    var segments =
      getSegments(
        path
      );


    var route =
      createBaseRoute(
        path,
        segments
      );


    /* =====================================================
       HOME
    ===================================================== */

    if (
      segments.length === 0
    ) {

      route.type =
        "home";


      route.canonicalPath =
        "/";


      route.canonicalURL =
        SITE_ORIGIN +
        "/";


      return route;

    }


    /* =====================================================
       LEGACY / BUSINESS
       -----------------------------------------------------
       /business/
       /business/abc-library/

       IMPORTANT:

       This block only recognizes old URLs.
       It NEVER generates them.
    ===================================================== */

    if (
      segments[0] ===
      "business"
    ) {

      route.isLegacyPage =
        true;


      route.isStaticPage =
        true;


      /*
       * Legacy:
       *
       * /business/<slug>/
       */

      if (
        segments.length === 2 &&
        segments[1]
      ) {

        route.type =
          "business";


        route.businessSlug =
          segments[1];


        route.canonicalPath =
          "/business/" +
          route.businessSlug +
          "/";


        route.canonicalURL =
          joinURL(
            route.canonicalPath
          );


        return route;

      }


      /*
       * Legacy:
       *
       * /business/
       */

      route.type =
        "business-index";


      route.canonicalPath =
        "/business/";


      route.canonicalURL =
        joinURL(
          route.canonicalPath
        );


      return route;

    }


    /* =====================================================
       RESERVED STATIC ROUTES
    ===================================================== */

    if (
      RESERVED_PATHS[
        segments[0]
      ]
    ) {

      route.type =
        "static";


      route.isStaticPage =
        true;


      return route;

    }


    /* =====================================================
       /in/
       SEO ROOT
    ===================================================== */

    if (
      isSEOPath(
        segments
      ) &&
      segments.length === 1
    ) {

      route.type =
        "seo-root";


      route.isSEOPage =
        true;


      route.canonicalPath =
        "/in/";


      route.canonicalURL =
        joinURL(
          route.canonicalPath
        );


      return route;

    }


    /* =====================================================
       STATE
       -----------------------------------------------------
       /in/bihar/
    ===================================================== */

    if (
      isSEOPath(
        segments
      ) &&
      segments.length === 2
    ) {

      route.type =
        "state";


      route.isSEOPage =
        true;


      route.isStatePage =
        true;


      route.stateSlug =
        segments[1];


      route.canonicalPath =
        "/in/" +
        route.stateSlug +
        "/";


      route.canonicalURL =
        joinURL(
          route.canonicalPath
        );


      return route;

    }


    /* =====================================================
       DISTRICT
       -----------------------------------------------------
       /in/bihar/siwan/
    ===================================================== */

    if (
      isSEOPath(
        segments
      ) &&
      segments.length === 3
    ) {

      route.type =
        "district";


      route.isSEOPage =
        true;


      route.isDistrictPage =
        true;


      route.stateSlug =
        segments[1];


      route.districtSlug =
        segments[2];


      route.canonicalPath =
        "/in/" +
        route.stateSlug +
        "/" +
        route.districtSlug +
        "/";


      route.canonicalURL =
        joinURL(
          route.canonicalPath
        );


      return route;

    }


    /* =====================================================
       CATEGORY
       -----------------------------------------------------
       /in/bihar/siwan/clothing-and-fashion/
    ===================================================== */

    if (
      isSEOPath(
        segments
      ) &&
      segments.length === 4
    ) {

      route.type =
        "category";


      route.isSEOPage =
        true;


      route.isCategoryPage =
        true;


      route.stateSlug =
        segments[1];


      route.districtSlug =
        segments[2];


      route.categorySlug =
        segments[3];


      route.canonicalPath =
        "/in/" +
        route.stateSlug +
        "/" +
        route.districtSlug +
        "/" +
        route.categorySlug +
        "/";


      route.canonicalURL =
        joinURL(
          route.canonicalPath
        );


      return route;

    }


    /* =====================================================
       BUSINESS
       -----------------------------------------------------
       /in/bihar/siwan/clothing-and-fashion/
       siwan-fashion-house/
    ===================================================== */

    if (
      isSEOPath(
        segments
      ) &&
      segments.length === 5
    ) {

      /*
       * CRITICAL:
       *
       * business-page.js expects:
       *
       * route.isBusinessPage === true
       */

      route.type =
        "business";


      route.isSEOPage =
        true;


      route.isBusinessPage =
        true;


      route.stateSlug =
        segments[1];


      route.districtSlug =
        segments[2];


      route.categorySlug =
        segments[3];


      route.businessSlug =
        segments[4];


      /*
       * Canonical permanent SEO path.
       */

      route.canonicalPath =
        "/in/" +
        route.stateSlug +
        "/" +
        route.districtSlug +
        "/" +
        route.categorySlug +
        "/" +
        route.businessSlug +
        "/";


      route.canonicalURL =
        joinURL(
          route.canonicalPath
        );


      return route;

    }


    /* =====================================================
       UNKNOWN
    ===================================================== */

    return route;

  }


  /* =======================================================
     URL BUILDERS
  ======================================================= */


  /* =======================================================
     HOME URL
  ======================================================= */

  function buildHomeURL() {

    return (
      SITE_ORIGIN +
      "/"
    );

  }


  /* =======================================================
     STATE URL
  ======================================================= */

  function buildStateURL(
    stateSlug
  ) {

    stateSlug =
      cleanSlug(
        stateSlug
      );


    if (
      !stateSlug
    ) {

      return buildHomeURL();

    }


    return joinURL(

      "/in/" +
      stateSlug +
      "/"

    );

  }


  /* =======================================================
     DISTRICT URL
  ======================================================= */

  function buildDistrictURL(
    stateSlug,
    districtSlug
  ) {

    stateSlug =
      cleanSlug(
        stateSlug
      );


    districtSlug =
      cleanSlug(
        districtSlug
      );


    if (
      !stateSlug ||
      !districtSlug
    ) {

      return buildHomeURL();

    }


    return joinURL(

      "/in/" +
      stateSlug +
      "/" +
      districtSlug +
      "/"

    );

  }


  /* =======================================================
     CATEGORY URL
  ======================================================= */

  function buildCategoryURL(
    stateSlug,
    districtSlug,
    categorySlug
  ) {

    stateSlug =
      cleanSlug(
        stateSlug
      );


    districtSlug =
      cleanSlug(
        districtSlug
      );


    categorySlug =
      cleanSlug(
        categorySlug
      );


    if (
      !stateSlug ||
      !districtSlug ||
      !categorySlug
    ) {

      return buildHomeURL();

    }


    return joinURL(

      "/in/" +
      stateSlug +
      "/" +
      districtSlug +
      "/" +
      categorySlug +
      "/"

    );

  }


  /* =======================================================
     BUSINESS URL
     -------------------------------------------------------
     IMPORTANT:

     ONLY permanent SEO URLs are generated.

     NEVER generate:

       /business/
       /business/<slug>/
       /business/<id>
  ======================================================= */

  function buildBusinessURL(
    stateSlug,
    districtSlug,
    categorySlug,
    businessSlug
  ) {

    stateSlug =
      cleanSlug(
        stateSlug
      );


    districtSlug =
      cleanSlug(
        districtSlug
      );


    categorySlug =
      cleanSlug(
        categorySlug
      );


    businessSlug =
      cleanSlug(
        businessSlug
      );


    /* =====================================================
       VALID PERMANENT SEO URL
    ===================================================== */

    if (
      stateSlug &&
      districtSlug &&
      categorySlug &&
      businessSlug
    ) {

      return joinURL(

        "/in/" +
        stateSlug +
        "/" +
        districtSlug +
        "/" +
        categorySlug +
        "/" +
        businessSlug +
        "/"

      );

    }


    /* =====================================================
       INVALID / INCOMPLETE SEO DATA

       DO NOT FALL BACK TO /business/
    ===================================================== */

    if (
      window.console &&
      typeof window.console.warn ===
        "function"
    ) {

      window.console.warn(

        "UBnux: Cannot build Business SEO URL. " +
        "Complete SEO data is required.",

        {

          stateSlug:
            stateSlug,

          districtSlug:
            districtSlug,

          categorySlug:
            categorySlug,

          businessSlug:
            businessSlug

        }

      );

    }


    /*
     * Prevent accidental navigation.
     */

    return "#";

  }


  /* =======================================================
     CURRENT ROUTE
  ======================================================= */

  function getCurrentRoute() {

    return parseRoute(

      (
        window.location &&
        window.location.pathname
      ) ||

      "/"

    );

  }


  /* =======================================================
     BUSINESS PAGE CHECK
  ======================================================= */

  function isBusinessPage(
    pathname
  ) {

    var route =
      parseRoute(
        pathname
      );


    return (

      route.type ===
        "business" &&

      route.isBusinessPage ===
        true &&

      Boolean(
        route.stateSlug
      ) &&

      Boolean(
        route.districtSlug
      ) &&

      Boolean(
        route.categorySlug
      ) &&

      Boolean(
        route.businessSlug
      )

    );

  }


  /* =======================================================
     SEO PAGE CHECK
  ======================================================= */

  function isSEOPage(
    pathname
  ) {

    var route =
      parseRoute(
        pathname
      );


    return (
      route.isSEOPage ===
      true
    );

  }


  /* =======================================================
     PUBLIC API
  ======================================================= */

  App.router = {

    SITE_ORIGIN:
      SITE_ORIGIN,

    SEO_PREFIX:
      SEO_PREFIX,

    RESERVED_PATHS:
      RESERVED_PATHS,

    normalizePath:
      normalizePath,

    cleanSlug:
      cleanSlug,

    getSegments:
      getSegments,

    parseRoute:
      parseRoute,

    getCurrentRoute:
      getCurrentRoute,

    isBusinessPage:
      isBusinessPage,

    isSEOPage:
      isSEOPage,

    buildHomeURL:
      buildHomeURL,

    buildStateURL:
      buildStateURL,

    buildDistrictURL:
      buildDistrictURL,

    buildCategoryURL:
      buildCategoryURL,

    buildBusinessURL:
      buildBusinessURL

  };


  /* =======================================================
     GLOBAL COMPATIBILITY HELPERS
  ======================================================= */

  App.getCurrentRoute =
    getCurrentRoute;


  App.buildBusinessURL =
    buildBusinessURL;


  App.buildCategoryURL =
    buildCategoryURL;


  App.buildDistrictURL =
    buildDistrictURL;


  App.buildStateURL =
    buildStateURL;


  /* =======================================================
     GLOBAL COMPATIBILITY ALIASES
  ======================================================= */

  window.UBnux =
    App;


  window.ZilaBiz =
    App;


  window.App =
    App;


  /* =======================================================
     DEBUG HELPER
  ======================================================= */

  if (
    window.console &&
    typeof window.console.debug ===
      "function"
  ) {

    window.console.debug(
      "UBnux SEO Router 2.2.0 initialized."
    );

  }


})(window);
